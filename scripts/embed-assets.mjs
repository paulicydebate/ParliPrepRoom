// Bundle the built app (dist/) into the worker as a generated module, so a
// deploy is a single script upload. (The Claude cloud sandbox's credential
// proxy rewrites the one-time token Cloudflare uses for separate asset
// uploads, so `assets` uploads fail from there.)
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { execSync } from 'node:child_process';

let build = 'dev';
try {
  build = execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
} catch {
  /* not a git checkout */
}

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.json': 'application/json',
};

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = {};
for (const path of walk('dist')) {
  const rel = '/' + relative('dist', path).split('\\').join('/');
  if (rel === '/preview.html') continue; // claude.ai preview only
  const ext = rel.slice(rel.lastIndexOf('.'));
  const type = TYPES[ext];
  if (!type) continue;
  files[rel] = { type, body: readFileSync(path, 'utf8') };
}
writeFileSync('worker/static.gen.ts', `// Generated by scripts/embed-assets.mjs. Do not edit.\nexport const FILES: Record<string, { type: string; body: string }> = ${JSON.stringify(files)};\nexport const BUILD = ${JSON.stringify(build)};\n`);
console.log(`Embedded ${Object.keys(files).length} files`);
